#include <iostream>
using namespace std;
int main()
{
    cout << "Hello\nWorld\n!"<<"\n"; // The \n is an escape sequence that represents a new line. When this line is executed, it will output "Hello" followed by a new line, then "World" followed by another new line, and finally "!" followed by a new line. The output will look like this:
/*
Hello
World
!
*/  
    return 0;
}
