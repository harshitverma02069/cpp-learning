#include <iostream>
using namespace std;

int main()
{
    double pi = 3.14159; // Declare a double variable named 'pi' and initialize it with the value 3.14159
    
    cout << "The value of pi is: " << pi << "\n"; // Output the value of 'pi' to the console
    
    return 0;
}
