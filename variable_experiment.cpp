#include <iostream>
using namespace std;
int main()
{
    int harshit = 100;
    cout << harshit << "\n";
    harshit = 200; // We can change the value of 'harshit' because it is a variable, which allows us to store and modify data.
    cout << harshit << "\n";
    harshit = 300; // We can change the value of 'harshit' again to demonstrate that variables can be updated multiple times throughout the program.
    cout << harshit << "\n";
    return 0;
}