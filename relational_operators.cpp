#include <iostream>
using namespace std;

int main ()
{
    cout << (5 > 3) << "\n"; 
    cout << (5 < 3) << "\n"; 
    cout << (1 != 2) << "\n";
    cout << (1 != 1) << "\n";
    cout << (1 == 2) << "\n";
    cout << (1 == 1) << "\n";
    cout << (5 >= 6) << "\n";
    cout << (5 >= 3) << "\n";
    cout << (5 >= 5) << "\n";
    cout << (5 <= 3) << "\n";
    cout << (5 <= 6) << "\n";
    cout << (5 <= 5) << "\n";

    return 0;
}