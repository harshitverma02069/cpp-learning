#include <iostream>
using namespace std;

int main()
{
    int a = 10;
    int b = 3;

    cout << a + b << "\n";
    cout << a - b << "\n";
    cout << a * b << "\n";
    cout << a / b << "\n";
    cout << a % b << "\n";

    return 0;

}

/*
Operator        Meaning

+               addition
-               subtraction
*               multiplication
/               division
%               modulus/remainder

Also ;

Integer division:

(10/3) = 3

because both are integers.

*/